# Builds the FX flash data for Gettin' Tired and writes fxdata.h for the sketch.
# Run title_text.py first, then:  python3 fxpack.py
# psi_tire.npy holds the pressure-screen tire at every PSI (recorded from the game's old drawing code).
import os, sys, numpy as np
ART = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ART, '..', 'TireTester')
def bitmap(m):                                      # FX bitmap: width, height (16-bit), then 8-row pages of columns
    H, W = m.shape
    return bytes([W >> 8, W & 255, H >> 8, H & 255]) + bytes(
        sum(int(p * 8 + k < H and m[p * 8 + k, x]) << k for k in range(8)) for p in range((H + 7) // 8) for x in range(W))
def ink(m):                                         # masked FX bitmap: black ink where m is set, see-through elsewhere
    H, W = m.shape; out = bytearray([W >> 8, W & 255, H >> 8, H & 255])
    for p in range((H + 7) // 8):
        for x in range(W):
            out += bytes([0, sum(int(p * 8 + k < H and m[p * 8 + k, x]) << k for k in range(8))])
    return bytes(out)
def sprite(frames):                                 # masked FX sprite, frames of (ink, solid): black ink, white solid, rest see-through
    n, _, H, W = frames.shape; out = bytearray([W >> 8, W & 255, H >> 8, H & 255])
    for ink_, sol in frames:
        for p in range((H + 7) // 8):
            for x in range(W):
                rows = [p * 8 + k for k in range(8)]
                img = sum(int(r < H and sol[r, x] and not ink_[r, x]) << k for k, r in enumerate(rows))
                msk = sum(int(r < H and (sol[r, x] or ink_[r, x])) << k for k, r in enumerate(rows))
                out += bytes([img, msk])
    return bytes(out)
S = np.load(os.path.join(ART, 'sprites.npz'))
TR = np.load(os.path.join(ART, 'tread.npz'))   # run tread.py first
L = np.load(os.path.join(ART, 'lettering.npz'))
def psitire():                                      # 5 x 31 frames, white = 1, drawn over the screen as is
    F = np.load(os.path.join(ART, 'psi_types.npy')).reshape(-1, 46, 51); n, H, W = F.shape   # run psi_types.py first
    return bytes([W >> 8, W & 255, H >> 8, H & 255]) + b''.join(bitmap(f)[4:] for f in F)
parts = [
    ('FX_TITLE',    ink(L['title']),    "TIRE TESTER lettering"),
    ('FX_GAMEOVER', ink(L['gameover']), 'GAME OVER'),
    ('FX_NEWREC',   ink(L['newrec']),   'NEW RECORD'),
    ('FX_PSITIRE',  psitire(),             'tire on the pressure screen, 5 types x 31 frames for 15..45 PSI, 51x46'),
    ('FX_BIRD',     sprite(S['bird']),  'bird, 2 flap frames, 17x11'),
    ('FX_CLOUD',    sprite(S['cloud']), 'cloud, 46x18'),
    ('FX_BLIMP',    sprite(S['blimp']), 'blimp, 60x24'),
    ('FX_TRUCK',    sprite(S['truck']), 'pickup truck, 50x22'),
    ('FX_TREAD',    sprite(TR['small'].reshape(40, 2, 33, 33)), 'tread band, 5 types x 8 turn frames, 33x33 (r13)'),
    ('FX_TREADB',   sprite(TR['big'].reshape(40, 2, 51, 51)),   'tread band, 5 types x 8 turn frames, 51x51 (r22)'),
    ('FX_HERO',     sprite(np.load(os.path.join(ART, 'hero.npy'))), 'big tire guy for title + sound: smile, blink, squash, asleep; 40x46 (run hero.py)'),
    ('FX_HUBCAP',   sprite(S['hubcap']), 'hubcap pickup, 9x9'),
    ('FX_TRAMP',    sprite(S['tramp']), 'trampoline 24x9, frame 1 = sagging'),
    ('FX_BOOST',    sprite(S['boost']), 'boost arrows 18x7, 2 frames'),
    ('FX_RING',     sprite(S['ring']),  'boost ring 7x25, 2 frames'),
    ('FX_STACK',    sprite(S['stack']), 'tire stack 3/4/5 high, 20x35'),
    ('FX_BUMP',     sprite(S['bump']),  'speed bump 12x5'),
    ('FX_TACH',     sprite(np.load(os.path.join(ART, 'tach.npy'))), 'big rev counter face with numbers, 48x48 (run tach.py)'),
]
data = bytearray(); hdr = []
for name, blob, note in parts:
    hdr.append('constexpr uint24_t %-11s = 0x%06X;   // %s' % (name, len(data), note))
    data += blob
while len(data) % 256: data.append(0xFF)
page = 0x10000 - len(data) // 256
os.makedirs(os.path.join(OUT, 'fxdata'), exist_ok=True)
open(os.path.join(OUT, 'fxdata', 'fxdata.bin'), 'wb').write(data)
h = '// generated by art/fxpack.py - do not edit\n#pragma once\n#include <ArduboyFX.h>\n'
h += 'constexpr uint16_t FX_DATA_PAGE = 0x%04X;   // %d bytes of FX data\n' % (page, len(data))
h += '\n'.join(hdr) + '\n'
open(os.path.join(OUT, 'fxdata.h'), 'w').write(h)
print(h)
